/**
 * Builds the QR Code content containing ALL 17 verified points
 * (2, 41, 44, 45, 46, 50, 51, 52, 64, 75, 77, 78, 110, 121, 122, 127, 128)
 * plus Question No. 43 Interview Serial Number, official verification reference ID and IST timestamp.
 * Never includes OTP, passwords, or private credentials.
 */
export function buildAdmissionQrContent(payload: AdmissionVerificationPayload): string {
  const lines: string[] = [
    'NAND VIDHYA EDUCATION ACADEMY (NVEA)',
    'STATUS: ADMISSION & CONSENT OTP VERIFIED',
    `Record ID: ${payload.recordNumber}`,
    `OTP Verification ID: ${payload.verificationId}`,
    `Verified (IST): ${payload.verificationDateIst} ${payload.verificationTimeIst}`,
    '--- OFFICIAL VERIFIED ADMISSION DATA ---',
  ];

  payload.seventeenPoints.forEach((pt) => {
    lines.push(`Point ${pt.pointNumber}. ${pt.label}: ${pt.value}`);
  });

  return lines.join('\n');
}

export function buildAdmissionVerifyUrl(payload: AdmissionVerificationPayload): string {
  const origin =
    typeof window !== 'undefined' && window.location?.origin && window.location.origin !== 'null'
      ? window.location.origin
      : 'https://www.nvea.in';

  return `${origin}/?verify=${encodeURIComponent(payload.recordNumber)}`;
}

export async function generateAdmissionQrDataUrl(
  payload: AdmissionVerificationPayload
): Promise<string> {
  const qrText = buildAdmissionQrContent(payload);
  try {
    return await QRCode.toDataURL(qrText, {
      errorCorrectionLevel: 'M',
      margin: 1,
      width: 340,
      color: {
        dark: '#0F2942',
        light: '#FFFFFF',
      },
    });
  } catch {
    return '';
  }
}

/**
 * Generates a high-resolution transparent PNG of the Official NVEA Admission Confirmation
 * & OTP Verified circular institutional rubber stamp/seal.
 * Preserves the exact existing round seal design, colors, border, font appearance, and format.
 */
export function generateAdmissionConfirmedSealPng(
  payload: AdmissionVerificationPayload
): string {
  if (typeof document === 'undefined') return '';
  const size = 460;
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d');
  if (!ctx) return '';

  const cx = size / 2;
  const cy = size / 2;

  ctx.clearRect(0, 0, size, size);
  ctx.save();

  // Slight authentic rubber-stamp rotation (-5 degrees)
  ctx.translate(cx, cy);
  ctx.rotate((-5 * Math.PI) / 180);
  ctx.translate(-cx, -cy);

  // Soft inner tint
  ctx.fillStyle = 'rgba(245, 243, 255, 0.78)';
  ctx.beginPath();
  ctx.arc(cx, cy, 208, 0, Math.PI * 2);
  ctx.fill();

  // Outer scalloped / double institutional purple-indigo border (#5B21B6 / #1E3A8A)
  ctx.strokeStyle = '#5B21B6';
  ctx.lineWidth = 8;
  ctx.beginPath();
  ctx.arc(cx, cy, 206, 0, Math.PI * 2);
  ctx.stroke();

  ctx.strokeStyle = '#1E3A8A';
  ctx.lineWidth = 2.5;
  ctx.beginPath();
  ctx.arc(cx, cy, 194, 0, Math.PI * 2);
  ctx.stroke();

  // Inner concentric ring
  ctx.strokeStyle = '#5B21B6';
  ctx.lineWidth = 3;
  ctx.beginPath();
  ctx.arc(cx, cy, 140, 0, Math.PI * 2);
  ctx.stroke();

  ctx.setLineDash([5, 4]);
  ctx.strokeStyle = '#008FD5';
  ctx.lineWidth = 1.5;
  ctx.beginPath();
  ctx.arc(cx, cy, 132, 0, Math.PI * 2);
  ctx.stroke();
  ctx.setLineDash([]);

  // Draw curved text helper
  const drawCurvedText = (
    text: string,
    radius: number,
    startAngle: number,
    endAngle: number,
    bottom = false
  ) => {
    ctx.save();
    ctx.font = 'bold 17px "Plus Jakarta Sans", Georgia, serif';
    ctx.fillStyle = '#4C1D95';
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    const chars = text.split('');
    const angleSpan = endAngle - startAngle;
    const step = chars.length > 1 ? angleSpan / (chars.length - 1) : 0;

    chars.forEach((ch, idx) => {
      const angle = startAngle + idx * step;
      ctx.save();
      ctx.translate(cx + Math.cos(angle) * radius, cy + Math.sin(angle) * radius);
      ctx.rotate(bottom ? angle - Math.PI / 2 : angle + Math.PI / 2);
      ctx.fillText(ch, 0, 0);
      ctx.restore();
    });
    ctx.restore();
  };

  // Top arc: NAND VIDHYA EDUCATION ACADEMY (NVEA)
  drawCurvedText(
    '★ NAND VIDHYA EDUCATION ACADEMY (NVEA) ★',
    167,
    -Math.PI * 0.88,
    -Math.PI * 0.12,
    false
  );

  // Bottom arc: ADMISSION CONFIRMED • SINCE 2006
  drawCurvedText(
    '• ADMISSION CONFIRMED • SINCE 2006 •',
    167,
    Math.PI * 0.84,
    Math.PI * 0.16,
    true
  );

  // Center NVEA Identity inside inner circle
  ctx.textAlign = 'center';
  ctx.font = 'bold 38px "Plus Jakarta Sans", Georgia, serif';
  ctx.fillStyle = '#F27A24';
  ctx.fillText('N', cx - 44, cy - 68);
  ctx.fillStyle = '#93278F';
  ctx.fillText('VEA', cx + 14, cy - 68);

  // Cyan bar & Hindi नव्या
  ctx.fillStyle = '#008FD5';
  ctx.fillRect(cx - 72, cy - 60, 144, 5);
  ctx.font = 'bold 30px "Noto Sans Devanagari", sans-serif';
  ctx.fillText('नव्या', cx, cy - 30);

  // Central green ribbon banner: ADMISSION CONFIRMED & OTP VERIFIED
  ctx.fillStyle = '#047857';
  ctx.fillRect(cx - 178, cy - 16, 356, 38);
  ctx.strokeStyle = '#F59E0B';
  ctx.lineWidth = 2;
  ctx.strokeRect(cx - 178, cy - 16, 356, 38);

  ctx.fillStyle = '#FFFFFF';
  ctx.font = 'bold 17px "Plus Jakarta Sans", sans-serif';
  ctx.fillText('✓ ADMISSION CONFIRMED', cx, cy + 8);

  // Below ribbon: OTP VERIFIED + Date + Verification ID
  ctx.fillStyle = '#991B1B';
  ctx.font = 'bold 15px "Plus Jakarta Sans", sans-serif';
  ctx.fillText('OTP VERIFIED & APPROVED', cx, cy + 44);

  ctx.fillStyle = '#0F2942';
  ctx.font = 'bold 12.5px "JetBrains Mono", monospace';
  ctx.fillText(`DATE: ${payload.verificationDateIst}`, cx, cy + 66);

  ctx.fillStyle = '#475569';
  ctx.font = '600 11px "JetBrains Mono", monospace';
  ctx.fillText(`REF: ${payload.recordNumber}`, cx, cy + 86);

  ctx.fillStyle = '#5B21B6';
  ctx.font = 'italic bold 12px Georgia, serif';
  ctx.fillText('Authorized Digital Seal • NVEA', cx, cy + 108);

  ctx.restore();
  return canvas.toDataURL('image/png');
}
