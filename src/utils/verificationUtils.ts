export function formatIstDateTime(isoOrDateStr?: string): {
  dateIst: string;
  timeIst: string;
  fullIst: string;
} {
  let d = new Date();
  if (isoOrDateStr) {
    const parsed = new Date(isoOrDateStr);
    if (!isNaN(parsed.getTime())) {
      d = parsed;
    }
  }
  try {
    const dateIst = d.toLocaleDateString('en-IN', {
      timeZone: 'Asia/Kolkata',
      day: '2-digit',
      month: 'short',
      year: 'numeric',
    });
    const timeIst =
      d.toLocaleTimeString('en-IN', {
        timeZone: 'Asia/Kolkata',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
        hour12: true,
      }) + ' IST';
    return {
      dateIst,
      timeIst,
      fullIst: `${dateIst}, ${timeIst}`,
    };
  } catch {
    const fallback = d.toISOString().replace('T', ' ').slice(0, 19) + ' IST';
    return {
      dateIst: fallback.slice(0, 10),
      timeIst: fallback.slice(11),
      fullIst: fallback,
    };
  }
}

/**
 * Extracts a single consistent verified data snapshot from the form answers
 * (with fallback to live DOM input elements if needed).
 * Used identically across Confirmation Email, QR Code, Round Seal, and Record Summary.
 */
export function extractVerificationPayload(
  recordNumber: string,
  answers: Record<string, string | string[]>,
  fallbackVerifiedAtIso?: string,
  explicitVerifiedContact?: string
): AdmissionVerificationPayload {
  const str = (...keys: string[]): string => {
    for (const key of keys) {
      const val = answers[key];
      if (Array.isArray(val)) {
        const joined = val.filter((v) => String(v).trim() !== '').join(', ').trim();
        if (joined) return joined;
      } else if (typeof val === 'string' && val.trim() !== '') {
        return val.trim();
      }
      if (typeof document !== 'undefined') {
        const el = document.getElementById(`input-${key}`) as
          | HTMLInputElement
          | HTMLSelectElement
          | HTMLTextAreaElement
          | null;
        if (el && typeof el.value === 'string' && el.value.trim() !== '') {
          return el.value.trim();
        }
      }
    }
    return '';
  };

  const rawVerifiedVal = str('q171');
  const idMatch = rawVerifiedVal.match(/(NVEA-(?:OTP|GAS)-[A-Z0-9]+)/i);
  const cleanRec = recordNumber.replace(/[^A-Z0-9]/gi, '');
  const verificationId = idMatch ? idMatch[1].toUpperCase() : `NVEA-OTP-${cleanRec}`;

  const emailMatch = rawVerifiedVal.match(/\(([^•)]+@[^•)]+)/);
  const verifiedContact =
    (explicitVerifiedContact && explicitVerifiedContact.trim()) ||
    (emailMatch ? emailMatch[1].trim() : '') ||
    '';

  const verifiedIso = fallbackVerifiedAtIso || new Date().toISOString();
  const { dateIst, timeIst } = formatIstDateTime(verifiedIso);

  // Question No. 43 Interview Serial Number (Auto-generated upon OTP verification)
  const cleanNum = cleanRec.replace(/^NVEA/i, '') || cleanRec || `${new Date().getFullYear()}01`;
  const rawIsn = str('q40', 'q130');
  const autoGeneratedIsn = `NVEA-ISN-${cleanNum}`;
  const interviewSerialNumber =
    rawIsn && rawIsn.trim() !== '' && rawIsn.trim() !== '—'
      ? rawIsn.trim()
      : autoGeneratedIsn;

  // Exact points from the form
  const applicantName = str('q2') || '—'; // Point 2
  const enrollmentDate = str('q38', 'q143') || '—'; // Point 41
  const srNumber = str('q41', 'q131') || '—'; // Point 44
  const registrationNumber = str('q42', 'q132') || '—'; // Point 45
  const enrollmentNumber = str('q43', 'q133') || '—'; // Point 46
  const totalActiveApplicantNumber = str('q47', 'q135') || '—'; // Point 50
  const applicantAllottedNumber = str('q48', 'q136') || '—'; // Point 51
  const enrollmentCollectNumber = str('q49', 'q134') || '—'; // Point 52
  const packageDuration = str('q61', 'q148') || '—'; // Point 64
  const clap = str('q72') || '—'; // Point 75
  const clapName = str('q74', 'q145') || '—'; // Point 77
  const clapSubjectName = str('q75', 'q146') || '—'; // Point 78
  const finalPayableFees = str('q107', 'q163') || '—'; // Point 110
  const oathCertificationNumber = str('q118') || '—'; // Point 121
  const deponentName = str('q119') || '—'; // Point 122
  const oathNumber = str('q124') || '—'; // Point 127
  const consentNumber = str('q125') || '—'; // Point 128

  const seventeenPoints: SeventeenPointItem[] = [
    { pointNumber: 2, label: 'Applicant Name', value: applicantName },
    { pointNumber: 41, label: 'Enrollment Date', value: enrollmentDate },
    { pointNumber: 43, label: 'Interview Serial Number', value: interviewSerialNumber },
    { pointNumber: 44, label: 'SR Number', value: srNumber },
    { pointNumber: 45, label: 'Registration Number', value: registrationNumber },
    { pointNumber: 46, label: 'Enrollment Number', value: enrollmentNumber },
    { pointNumber: 50, label: 'Total Active Applicant Number', value: totalActiveApplicantNumber },
    { pointNumber: 51, label: 'Applicant Allotted Number', value: applicantAllottedNumber },
    { pointNumber: 52, label: 'Enrollment Collect Number', value: enrollmentCollectNumber },
    { pointNumber: 64, label: 'Package Duration', value: packageDuration },
    { pointNumber: 75, label: 'CLAP', value: clap },
    { pointNumber: 77, label: 'CLAP Name', value: clapName },
    { pointNumber: 78, label: 'CLAP Subject Name', value: clapSubjectName },
    { pointNumber: 110, label: 'Final Payable Fees', value: finalPayableFees },
    { pointNumber: 121, label: 'Oath Certification Number', value: oathCertificationNumber },
    { pointNumber: 122, label: 'Deponent Name', value: deponentName },
    { pointNumber: 127, label: 'Oath Number', value: oathNumber },
    { pointNumber: 128, label: 'Consent Number', value: consentNumber },
  ];

  // Genuine system-generated verification/authentication/reference identifiers for the Summary Box
  const suffix = verificationId.replace(/^NVEA-(?:OTP|GAS)-/i, '') || cleanRec;
  const consentReferenceNumber = `NVEA-CR-${cleanRec}`;
  const consentCertificationId = `NVEA-CC-${suffix}`;
  const sealRegistrationNumber = `NVEA-SEAL-${cleanRec}`;
  const departmentalRecordNumber = `NVEA-DR-${cleanRec}`;
  const oathRegistrationDate = str('q128') || dateIst;

  const summaryIdentifiers: VerificationSummaryItem[] = [
    { label: 'Point 43 — Interview Serial Number', value: interviewSerialNumber },
    { label: 'Admission / Form Reference ID', value: recordNumber },
    { label: 'OTP Verification ID', value: verificationId },
    { label: 'Consent Reference Number', value: consentReferenceNumber },
    { label: 'Official Consent Certification ID', value: consentCertificationId },
    { label: 'Seal & Stamp Registration No.', value: sealRegistrationNumber },
    { label: 'Departmental Record No.', value: departmentalRecordNumber },
    ...(oathRegistrationDate
      ? [{ label: 'Oath Registration Date', value: oathRegistrationDate }]
      : []),
    ...(verifiedContact
      ? [{ label: 'OTP Verified Gmail ID', value: verifiedContact }]
      : []),
    { label: 'Consent Verification Status', value: 'VERIFIED & CONFIRMED' },
    { label: 'Oath Verification Status', value: 'VERIFIED & APPROVED' },
    { label: 'Gmail / OTP Verification Status', value: 'OTP VERIFIED' },
    { label: 'Verification Date (IST)', value: dateIst },
    { label: 'Verification Time (IST)', value: timeIst },
  ];

  return {
    recordNumber,
    verificationId,
    consentReferenceNumber,
    consentCertificationId,
    sealRegistrationNumber,
    departmentalRecordNumber,
    oathRegistrationDate,
    verifiedContact,
    verificationDateIst: dateIst,
    verificationTimeIst: timeIst,
    verifiedAtIso: verifiedIso,
    consentStatus: 'VERIFIED & CONFIRMED',
    oathStatus: 'VERIFIED & APPROVED',
    otpStatus: 'OTP VERIFIED',
    admissionDate: enrollmentDate !== '—' ? enrollmentDate : dateIst,
    courseClass: clapName !== '—' ? clapName : clap,
    verifiedAt: `${dateIst}, ${timeIst}`,
    interviewSerialNumber,
    applicantName,
    enrollmentDate,
    srNumber,
    registrationNumber,
    enrollmentNumber,
    totalActiveApplicantNumber,
    applicantAllottedNumber,
    enrollmentCollectNumber,
    packageDuration,
    clap,
    clapName,
    clapSubjectName,
    finalPayableFees,
    oathCertificationNumber,
    deponentName,
    oathNumber,
    consentNumber,
    seventeenPoints,
    summaryIdentifiers,
  };
}

